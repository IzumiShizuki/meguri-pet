/**
 * Installs the Meguri work preset into the user's DeepSeek Harness home.
 *
 * The preset is a byte-level contract: it is the exact agent composition the
 * work session is created with. Meguri never edits an existing preset, never
 * replaces the user's global defaults, and never writes anything else into
 * DSH_HOME.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const WORK_PRESET_ID = 'meguri-work-v1'
export const WORK_PRESET_DIRECTORY = '.agent-presets'

const PRESET_PERSONA_PREFIX =
  'Complete only the user-confirmed task using your native tools. '
  + 'Do not create or delegate to agents. '
  + 'Respect project instructions and native approval requests. '
  + 'Keep the reply short and factual; the desktop companion shows it verbatim.'

/**
 * The composition is intentionally small: a persona fence, the Windows shell,
 * the file tools and the deliverable presenter. Sandbox policy, approval
 * routing, persistence and model selection stay owned by the Host, so this
 * file grants no capability on its own.
 */
export const WORK_PRESET_CONTENTS = `# Meguri work preset. Generated by the Meguri desktop pet.
# Sandbox, approval, persistence and model host are unchanged by this file.
- id: persona
  name: '@deepseek-ai/dsh-persona'
  config:
    prefix: ${JSON.stringify(PRESET_PERSONA_PREFIX)}
    suffix: 'Your working directory is {{cwd}}.'
- id: tool-pwsh
  name: '@deepseek-ai/dsh-tool-pwsh'
  config:
    disabled: !!js process.platform !== 'win32'
- id: tool-bash
  name: '@deepseek-ai/dsh-tool-bash'
  config:
    disabled: !!js process.platform === 'win32'
- id: tool-fs
  name: '@deepseek-ai/dsh-tool-fs'
- id: tool-fs-search
  name: '@deepseek-ai/dsh-tool-fs-search'
  config:
    sampleOverCapGlobResults: false
- id: tool-todo
  name: '@deepseek-ai/dsh-tool-todo'
  config:
    allowParallelInProgress: true
- id: tool-web
  name: '@deepseek-ai/dsh-tool-web'
  config:
    fetch: true
    searchTimeoutMs: 60000
- id: present
  name: '@deepseek-ai/dsh-tool-present'
`

export const WORK_PRESET_METADATA = 'name: Meguri work\ndescription: Execute one user-confirmed small task with native tools and approvals.\n'

export function workPresetFiles(dshHome) {
  const directory = join(dshHome, WORK_PRESET_DIRECTORY, WORK_PRESET_ID)
  return {
    directory,
    composition: join(directory, 'agent.cordis.yml'),
    metadata: join(directory, 'preset.yml'),
  }
}

export function workPresetReady(dshHome, options = {}) {
  const files = workPresetFiles(dshHome)
  const readFile = options.readFile ?? readFileSync
  try {
    return String(readFile(files.composition)) === WORK_PRESET_CONTENTS
  }
  catch {
    return false
  }
}

/**
 * Writes the preset only when the exact expected composition is not already
 * present. An existing file with different contents belongs to the user (or to
 * a newer Meguri) and is never overwritten.
 */
export function installWorkPreset(dshHome, options = {}) {
  if (typeof dshHome !== 'string' || !dshHome.trim())
    return { installed: false, reason: 'invalid_home' }
  const exists = options.exists ?? existsSync
  const readFile = options.readFile ?? readFileSync
  const writeFile = options.writeFile ?? writeFileSync
  const makeDirectory = options.mkdir ?? mkdirSync
  const files = workPresetFiles(dshHome)

  if (workPresetReady(dshHome, { readFile }))
    return { installed: false, reason: 'present', ...files }
  if (exists(files.composition))
    return { installed: false, reason: 'user_preset', ...files }

  try {
    makeDirectory(join(dshHome, WORK_PRESET_DIRECTORY), { recursive: true })
    makeDirectory(files.directory, { recursive: true })
    writeFile(files.composition, WORK_PRESET_CONTENTS, { encoding: 'utf8', flag: 'wx' })
    if (!exists(files.metadata))
      writeFile(files.metadata, WORK_PRESET_METADATA, { encoding: 'utf8', flag: 'wx' })
    return { installed: true, reason: 'created', ...files }
  }
  catch (error) {
    return {
      installed: false,
      reason: error?.code === 'EEXIST' ? 'user_preset' : 'unavailable',
      ...files,
    }
  }
}
